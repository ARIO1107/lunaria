import { test, expect } from '@playwright/test';
import { skipSiteIntro } from './siteIntro.js';

test('the terminal keeps its layout and supports keyboard navigation', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const lunar = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/assets/menu/lunar.png'));
  await page.goto('/');
  await skipSiteIntro(page);
  expect((await lunar).ok()).toBe(true);
  const menu = page.getByRole('navigation', { name: 'Main menu' });
  await expect(menu.getByRole('button', { name: /^Continue/ })).toBeDisabled();
  await expect(page.getByRole('img', { name: 'Lunaria', exact: true })).toBeVisible();
  await expect(page.locator('.terminal-logo-mark img')).toHaveJSProperty('naturalWidth', 1024);
  await page.keyboard.press('ArrowDown');
  const missions = menu.getByRole('button', { name: 'Select mission' });
  await expect(missions).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('dialog').getByText('Locked', { exact: true })).toHaveCount(5);
  await expect(page.getByRole('dialog').getByText('Available', { exact: true })).toHaveCount(1);
  await page.keyboard.press('Escape');
  await expect(missions).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await menu.getByRole('button', { name: 'Exit', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'End of transmission' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to menu' }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('the menu starts in english and the language button switches to spanish', async ({ page }) => {
  await page.goto('/');
  await skipSiteIntro(page);
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
  const english = page.getByRole('button', { name: 'English' });
  await expect(english).toHaveAttribute('aria-pressed', 'true');
  const wide = await english.boundingBox();
  expect(wide.width).toBeGreaterThanOrEqual(44);
  expect(wide.height).toBeGreaterThanOrEqual(44);
  await page.setViewportSize({ width: 760, height: 900 });
  const narrow = await english.boundingBox();
  expect(narrow.width).toBeGreaterThanOrEqual(44);
  expect(narrow.height).toBeGreaterThanOrEqual(44);
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Spanish' }).click();
  await expect(page.locator('html')).toHaveAttribute('lang', 'es');
  await expect(page.getByRole('button', { name: 'Jugar', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Español' })).toHaveAttribute('aria-pressed', 'true');
  await page.reload();
  const skipSpanish = page.getByRole('button', { name: 'Omitir intro' });
  const playSpanish = page.getByRole('button', { name: 'Jugar', exact: true });
  await skipSpanish.or(playSpanish).waitFor({ state: 'visible' });
  if (await skipSpanish.isVisible()) await skipSpanish.click();
  await expect(playSpanish).toBeVisible();
  await page.getByRole('button', { name: 'Inglés' }).click();
  await expect(page.locator('html')).toHaveAttribute('lang', 'en');
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
});

test('preferences and exploration progress survive a reload', async ({ page }) => {
  await page.clock.install();
  await page.goto('/');
  await skipSiteIntro(page);
  await page.getByRole('button', { name: 'Settings' }).click();
  await page.getByRole('checkbox', { name: 'Reduce animations' }).check();
  const volume = page.getByRole('slider', { name: 'Master volume' });
  await volume.focus();
  await page.keyboard.press('End');
  await expect(volume).toHaveValue('100');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await page.getByRole('button', { name: 'Skip cinematic' }).click();
  await expect(page.locator('.asset-loading')).toHaveCount(0, { timeout: 30000 });
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await page.locator('canvas').focus();
  await page.keyboard.down('ArrowRight');
  await page.clock.runFor(2400);
  await page.keyboard.up('ArrowRight');
  await expect(page.locator('.map-toolbar')).toContainText('Command bridge');
  await page.getByRole('button', { name: 'Main menu', exact: true }).click();
  await page.reload();
  await skipSiteIntro(page);
  await page.getByRole('button', { name: 'Settings' }).click();
  await expect(page.getByRole('checkbox', { name: 'Reduce animations' })).toBeChecked();
  await expect(page.getByRole('slider', { name: 'Master volume' })).toHaveValue('100');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.locator('.map-toolbar')).toContainText('Command bridge', { timeout: 30000 });
  await expect(page.locator('.zoom-controls')).toContainText('130 %');
});

